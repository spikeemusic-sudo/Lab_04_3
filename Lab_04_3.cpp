#include <iostream>
#include <iomanip>
#include <cmath>

using namespace std;

int main()
{
    // Оголошення змінних для параметрів, інтервалу табулювання та функції
    double a, b, c;
    double xp, xk, dx;
    double x, F;

    // Введення початкових даних з клавіатури
    cout << "a = "; cin >> a;
    cout << "b = "; cin >> b;
    cout << "c = "; cin >> c;
    cout << "xp = "; cin >> xp;
    cout << "xk = "; cin >> xk;
    cout << "dx = "; cin >> dx;

    // Встановлення фіксованого формату виведення дійсних чисел
    cout << fixed;

    // Виведення шапки таблиці
    cout << "---------------------------" << endl;
    cout << "|" << setw(7) << "x" << " |" << setw(12) << "F" << " |" << endl;
    cout << "---------------------------" << endl;

    // Цикл табулювання функції F від xp до xk з кроком dx
    x = xp;
    while (x <= xk)
    {
        // Обчислення значення функції відповідно до умов Варіанту 28
        if (c < 0 && a != 0)
        {
            F = -a * x * x;
        }
        else if (c > 0 && a == 0)
        {
            F = (a - x) / (c * x);
        }
        else
        {
            F = x / c;
        }

        // Форматне виведення рядка таблиці
        cout << "|" << setw(7) << setprecision(2) << x
            << " |" << setw(12) << setprecision(3) << F
            << " |" << endl;

        x += dx; // Збільшення аргументу на крок dx
    }

    // Нижній край таблиці
    cout << "---------------------------" << endl;

    return 0;
}